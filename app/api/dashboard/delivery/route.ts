import { NextResponse } from "next/server";
import { promises as fs } from "fs";
import path from "path";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

type DeliveryData = {
  shippingPrices: Record<string, { home: number; desk: number }>;
  officeLocations: Record<string, string[]>;
};

const DELIVERY_FILE = path.join(process.cwd(), "lib", "delivery.ts");
const MAX_PRICE = 1_000_000;
const MAX_OFFICES = 100;
const MAX_OFFICE_LENGTH = 120;

function extractObjectLiteral(source: string, exportName: string): string {
  const exportIndex = source.indexOf(`export const ${exportName}`);
  if (exportIndex === -1) {
    throw new Error(`Could not find export "${exportName}"`);
  }

  const equalsIndex = source.indexOf("=", exportIndex);
  const openIndex = source.indexOf("{", equalsIndex);
  if (equalsIndex === -1 || openIndex === -1) {
    throw new Error(`Could not find object for "${exportName}"`);
  }

  let depth = 0;
  let inString = false;
  let escaped = false;

  for (let index = openIndex; index < source.length; index += 1) {
    const char = source[index];

    if (inString) {
      if (escaped) escaped = false;
      else if (char === "\\") escaped = true;
      else if (char === '"') inString = false;
      continue;
    }

    if (char === '"') {
      inString = true;
    } else if (char === "{") {
      depth += 1;
    } else if (char === "}") {
      depth -= 1;
      if (depth === 0) return source.slice(openIndex, index + 1);
    }
  }

  throw new Error(`Unterminated object for "${exportName}"`);
}

function parseDelivery(source: string): DeliveryData {
  const shippingLiteral = extractObjectLiteral(source, "shippingPrices");
  const officesLiteral = extractObjectLiteral(source, "officeLocations");

  // The literals are generated by this route, so evaluating them is safe.
  const shippingPrices = new Function(`return (${shippingLiteral});`)() as DeliveryData["shippingPrices"];
  const officeLocations = new Function(`return (${officesLiteral});`)() as DeliveryData["officeLocations"];

  return { shippingPrices, officeLocations };
}

function serializeDelivery(data: DeliveryData): string {
  const wilayas = Object.keys(data.shippingPrices);
  const lines: string[] = [
    "export interface DeliveryPrice {",
    "  home: number;",
    "  desk: number;",
    "}",
    "",
    "export const shippingPrices: Record<string, DeliveryPrice> = {",
  ];

  for (const wilaya of wilayas) {
    const price = data.shippingPrices[wilaya];
    lines.push(`  ${JSON.stringify(wilaya)}: { home: ${price.home}, desk: ${price.desk} },`);
  }

  lines.push("};", "", "export const officeLocations: Record<string, string[]> = {");

  for (const wilaya of wilayas) {
    const offices = data.officeLocations[wilaya] ?? [];
    lines.push(`  ${JSON.stringify(wilaya)}: [${offices.map((office) => JSON.stringify(office)).join(", ")}],`);
  }

  lines.push("};", "");
  return lines.join("\n");
}

async function readDelivery(): Promise<DeliveryData> {
  const source = await fs.readFile(DELIVERY_FILE, "utf8");
  return parseDelivery(source);
}

function normalizeOffices(value: unknown): string[] | null {
  if (!Array.isArray(value)) return null;

  const seen = new Set<string>();
  const offices: string[] = [];

  for (const entry of value) {
    if (typeof entry !== "string") return null;
    const office = entry.trim();
    if (!office) continue;
    if (office.length > MAX_OFFICE_LENGTH) return null;
    if (seen.has(office)) continue;
    seen.add(office);
    offices.push(office);
  }

  if (offices.length > MAX_OFFICES) return null;
  return offices;
}

function normalizePrice(value: unknown): number | null {
  if (typeof value !== "number" && typeof value !== "string") return null;
  if (typeof value === "string" && value.trim() === "") return null;
  const price = Number(value);
  if (!Number.isFinite(price) || !Number.isInteger(price)) return null;
  if (price < 0 || price > MAX_PRICE) return null;
  return price;
}

export async function GET() {
  try {
    const data = await readDelivery();
    return NextResponse.json(data, { status: 200 });
  } catch (error) {
    console.error("[api/dashboard/delivery] read error:", error);
    return NextResponse.json({ error: "Could not read delivery data" }, { status: 500 });
  }
}

export async function PUT(request: Request) {
  try {
    const body = await request.json();
    const wilaya = typeof body?.wilaya === "string" ? body.wilaya : "";
    const home = normalizePrice(body?.home);
    const desk = normalizePrice(body?.desk);
    const offices = normalizeOffices(body?.offices);

    if (!wilaya) {
      return NextResponse.json({ error: "Missing wilaya" }, { status: 400 });
    }
    if (home === null || desk === null) {
      return NextResponse.json({ error: "Prices must be whole numbers between 0 and 1,000,000" }, { status: 400 });
    }
    if (offices === null) {
      return NextResponse.json({ error: "Offices must be a list of valid names" }, { status: 400 });
    }

    const current = await readDelivery();
    if (!current.shippingPrices[wilaya]) {
      return NextResponse.json({ error: "Unknown wilaya" }, { status: 404 });
    }

    const updated: DeliveryData = {
      shippingPrices: {
        ...current.shippingPrices,
        [wilaya]: { home, desk },
      },
      officeLocations: {
        ...current.officeLocations,
        [wilaya]: offices,
      },
    };

    const source = serializeDelivery(updated);
    const temporaryFile = `${DELIVERY_FILE}.${process.pid}.${Date.now()}.tmp`;

    await fs.writeFile(temporaryFile, source, "utf8");
    try {
      await fs.rename(temporaryFile, DELIVERY_FILE);
    } catch (error) {
      await fs.unlink(temporaryFile).catch(() => undefined);
      throw error;
    }

    return NextResponse.json({ success: true, ...updated }, { status: 200 });
  } catch (error) {
    console.error("[api/dashboard/delivery] write error:", error);
    return NextResponse.json({ error: "Could not update delivery data" }, { status: 500 });
  }
}
